const SAFE_LOGO_DATA_URI_REGEX =
  /^data:image\/(png|jpeg|webp|svg\+xml);base64,[a-zA-Z0-9+/=\s]+$/i;

interface InternalQrCodeStyling {
  _qr?: MinimalQrMatrix;
  _svg?: SVGSVGElement;
  _svgDrawingPromise?: Promise<void>;
}

interface LogoPlacementBox {
  x: number;
  y: number;
  width: number;
  height: number;
  rx: number;
  bgFill: string | null;
  innerX: number;
  innerY: number;
  innerWidth: number;
  innerHeight: number;
  source: string;
}

function encodeUtf8ToBase64(text: string): string {
  const bytes = new TextEncoder().encode(text);
  let binary = "";
  for (let i = 0; i < bytes.byteLength; i++) {
    binary += String.fromCharCode(bytes[i]!);
  }
  return btoa(binary);
}

function decodeBase64ToUtf8(base64: string): string {
  const clean = base64.replace(/\s+/g, "");
  const binary = atob(clean);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return new TextDecoder().decode(bytes);
}

function parseSvgNumericAttr(value: string | null, fallback: number): number {
  if (!value) {
    return fallback;
  }
  const parsed = Number.parseFloat(value.replace(/px$/i, "").trim());
  return Number.isFinite(parsed) ? Math.round(parsed) : fallback;
}

/**
 * Verifies that the current logo Data URI is safe and, if it is an SVG Data URI,
 * re-runs `sanitizeSvgContent` for defense-in-depth before embedding in exports.
 */
function verifyAndNormalizeLogoSource(rawSource: string): string {
  const trimmed = rawSource.trim();
  if (!SAFE_LOGO_DATA_URI_REGEX.test(trimmed)) {
    throw new Error("Unsafe or invalid logo Data URI rejected during export.");
  }

  if (/^data:image\/svg\+xml;base64,/i.test(trimmed)) {
    const commaIdx = trimmed.indexOf(",");
    const base64Part = commaIdx >= 0 ? trimmed.slice(commaIdx + 1) : "";
    const decodedSvg = decodeBase64ToUtf8(base64Part);
    const sanitized = sanitizeSvgContent(decodedSvg);
    if (!sanitized.isValid || !sanitized.dataUrl) {
      throw new Error(
        sanitized.error ?? "Uploaded SVG logo failed export security validation."
      );
    }
    return sanitized.dataUrl;
  }

  return trimmed;
}

/**
 * Post-processes the raw `<svg>` DOM generated by `qr-code-styling` into a
 * self-contained, standards-compliant vector SVG:
 * 1. Sets explicit `xmlns`, `width`, `height`, and `viewBox`.
 * 2. Normalizes `url('#id')` references to unquoted `url(#id)`.
 * 3. Removes the `fill="transparent"` background rectangle and its clipPath when
 *    transparent background is enabled so the SVG is genuinely transparent.
 * 4. Replaces `qr-code-styling`'s raw `<image>` element with a native vector
 *    `<g id="openqr-logo-group" clip-path="url(#openqr-logo-clip)">` containing
 *    the optional backing plate `<rect>` and a single-level `<image>` element.
 */
export function finalizeStandaloneSvgElement(
  svgElement: SVGSVGElement,
  design: QRDesign,
  pixelMargin: number,
  qrMatrix?: MinimalQrMatrix
): LogoPlacementBox | null {
  const doc = svgElement.ownerDocument;
  svgElement.setAttribute("width", String(design.width));
  svgElement.setAttribute("height", String(design.height));
  svgElement.setAttribute("viewBox", `0 0 ${design.width} ${design.height}`);
  svgElement.removeAttribute("xmlns:xlink");

  let defs = svgElement.querySelector("defs");
  if (!defs) {
    defs = doc.createElementNS("http://www.w3.org/2000/svg", "defs");
    svgElement.insertBefore(defs, svgElement.firstChild);
  }

  // Normalize quoted url('#...') references to standard url(#...)
  const allNodes = [svgElement, ...Array.from(svgElement.querySelectorAll("*"))];
  for (const node of allNodes) {
    for (const attr of Array.from(node.attributes)) {
      if (attr.value.includes("url(")) {
        const normalizedUrl = attr.value.replace(
          /url\(\s*['"]([^'"]+)['"]\s*\)/g,
          "url($1)"
        );
        if (normalizedUrl !== attr.value) {
          node.setAttribute(attr.name, normalizedUrl);
        }
      }
    }
  }

  // Handle background rect for transparent vs solid/gradient backgrounds
  const rects = Array.from(svgElement.querySelectorAll("rect"));
  for (const rect of rects) {
    const clipAttr = rect.getAttribute("clip-path") ?? "";
    if (clipAttr.includes("clip-path-background-color-")) {
      if (design.background.transparent) {
        const match = /#(clip-path-background-color-[^)\s'"]+)/.exec(clipAttr);
        if (match?.[1]) {
          const bgClip = svgElement.querySelector(`[id="${match[1]}"]`);
          bgClip?.parentNode?.removeChild(bgClip);
        }
        rect.parentNode?.removeChild(rect);
      } else {
        rect.setAttribute("data-qr-background", "true");
      }
    }
  }

  // Handle logo embedding & backing plate
  const rawImageEl = svgElement.querySelector("image");
  if (!design.logo?.source) {
    if (rawImageEl) {
      rawImageEl.parentNode?.removeChild(rawImageEl);
    }
    return null;
  }

  const verifiedLogoSource = verifyAndNormalizeLogoSource(design.logo.source);

  const fallbackGeo =
    qrMatrix
      ? computeLogoClearanceGeometry(
          qrMatrix.getModuleCount(),
          design.width,
          design.height,
          pixelMargin,
          design
        )
      : null;

  let x = parseSvgNumericAttr(
    rawImageEl?.getAttribute("x") ?? null,
    fallbackGeo?.x ?? Math.round(design.width * 0.4)
  );
  let y = parseSvgNumericAttr(
    rawImageEl?.getAttribute("y") ?? null,
    fallbackGeo?.y ?? Math.round(design.height * 0.4)
  );
  let width = parseSvgNumericAttr(
    rawImageEl?.getAttribute("width") ?? null,
    fallbackGeo?.boxWidth ?? Math.round(design.width * 0.2)
  );
  let height = parseSvgNumericAttr(
    rawImageEl?.getAttribute("height") ?? null,
    fallbackGeo?.boxHeight ?? Math.round(design.height * 0.2)
  );

  if (width <= 0 || height <= 0) {
    width = fallbackGeo?.boxWidth ?? Math.round(design.width * 0.2);
    height = fallbackGeo?.boxHeight ?? Math.round(design.height * 0.2);
    x = fallbackGeo?.x ?? Math.round((design.width - width) / 2);
    y = fallbackGeo?.y ?? Math.round((design.height - height) / 2);
  }

  const shape = design.logo.shape ?? "square";
  const rx =
    shape === "circle"
      ? Math.round(Math.min(width, height) / 2)
      : shape === "rounded"
        ? Math.round(Math.min(width, height) * (48 / 256))
        : 0;

  const rawBg = design.logo.backgroundColor?.trim();
  const hasValidBg = Boolean(
    rawBg && rawBg !== "transparent" && isValidHexColor(rawBg)
  );
  const bgFill = hasValidBg ? normalizeHexColor(rawBg!, "#FFFFFF") : null;

  const inset = hasValidBg ? Math.round(Math.min(width, height) * (24 / 256)) : 0;
  const innerX = x + inset;
  const innerY = y + inset;
  const innerWidth = Math.max(1, width - inset * 2);
  const innerHeight = Math.max(1, height - inset * 2);

  const existingLogoClip = defs.querySelector("#openqr-logo-clip");
  existingLogoClip?.parentNode?.removeChild(existingLogoClip);

  const clipPathEl = doc.createElementNS(
    "http://www.w3.org/2000/svg",
    "clipPath"
  );
  clipPathEl.setAttribute("id", "openqr-logo-clip");
  const clipRectEl = doc.createElementNS("http://www.w3.org/2000/svg", "rect");
  clipRectEl.setAttribute("x", String(x));
  clipRectEl.setAttribute("y", String(y));
  clipRectEl.setAttribute("width", String(width));
  clipRectEl.setAttribute("height", String(height));
  if (rx > 0) {
    clipRectEl.setAttribute("rx", String(rx));
    clipRectEl.setAttribute("ry", String(rx));
  }
  clipPathEl.appendChild(clipRectEl);
  defs.appendChild(clipPathEl);

  const logoGroup = doc.createElementNS("http://www.w3.org/2000/svg", "g");
  logoGroup.setAttribute("id", "openqr-logo-group");
  logoGroup.setAttribute("clip-path", "url(#openqr-logo-clip)");

  if (bgFill) {
    const plateRect = doc.createElementNS("http://www.w3.org/2000/svg", "rect");
    plateRect.setAttribute("data-logo-backing-plate", "true");
    plateRect.setAttribute("x", String(x));
    plateRect.setAttribute("y", String(y));
    plateRect.setAttribute("width", String(width));
    plateRect.setAttribute("height", String(height));
    if (rx > 0) {
      plateRect.setAttribute("rx", String(rx));
      plateRect.setAttribute("ry", String(rx));
    }
    plateRect.setAttribute("fill", bgFill);
    logoGroup.appendChild(plateRect);
  }

  const cleanImageEl = doc.createElementNS(
    "http://www.w3.org/2000/svg",
    "image"
  );
  cleanImageEl.setAttribute("href", verifiedLogoSource);
  cleanImageEl.setAttribute("x", String(innerX));
  cleanImageEl.setAttribute("y", String(innerY));
  cleanImageEl.setAttribute("width", String(innerWidth));
  cleanImageEl.setAttribute("height", String(innerHeight));
  cleanImageEl.setAttribute("preserveAspectRatio", "xMidYMid meet");
  logoGroup.appendChild(cleanImageEl);

  if (rawImageEl && rawImageEl.parentNode) {
    rawImageEl.parentNode.replaceChild(logoGroup, rawImageEl);
  } else {
    svgElement.appendChild(logoGroup);
  }

  return {
    x,
    y,
    width,
    height,
    rx,
    bgFill,
    innerX,
    innerY,
    innerWidth,
    innerHeight,
    source: verifiedLogoSource,
  };
}

function canUseBrowser2dCanvas(): boolean {
  if (typeof window === "undefined" || typeof document === "undefined") {
    return false;
  }
  if (window.navigator?.userAgent?.includes("jsdom")) {
    return false;
  }
  try {
    const testCanvas = document.createElement("canvas");
    testCanvas.width = 1;
    testCanvas.height = 1;
    const ctx = testCanvas.getContext("2d");
    testCanvas.width = 0;
    testCanvas.height = 0;
    return Boolean(ctx && typeof testCanvas.toBlob === "function");
  } catch {
    return false;
  }
}

function loadImageElement(dataUri: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = () =>
      reject(new Error("Failed to decode image resource during QR export."));
    img.src = dataUri;
  });
}

function traceRoundedRectPath(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  width: number,
  height: number,
  radius: number
): void {
  const r = Math.max(0, Math.min(radius, Math.min(width, height) / 2));
  ctx.beginPath();
  if (r === 0) {
    ctx.rect(x, y, width, height);
    ctx.closePath();
    return;
  }
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + width - r, y);
  ctx.quadraticCurveTo(x + width, y, x + width, y + r);
  ctx.lineTo(x + width, y + height - r);
  ctx.quadraticCurveTo(x + width, y + height, x + width - r, y + height);
  ctx.lineTo(x + r, y + height);
  ctx.quadraticCurveTo(x, y + height, x, y + height - r);
  ctx.lineTo(x, y + r);
  ctx.quadraticCurveTo(x, y, x + r, y);
  ctx.closePath();
}

function drawLogoPreserveAspectRatio(
  ctx: CanvasRenderingContext2D,
  img: HTMLImageElement,
  boxX: number,
  boxY: number,
  boxW: number,
  boxH: number
): void {
  const natW = img.naturalWidth || img.width || boxW;
  const natH = img.naturalHeight || img.height || boxH;
  if (natW <= 0 || natH <= 0) {
    ctx.drawImage(img, boxX, boxY, boxW, boxH);
    return;
  }
  const scale = Math.min(boxW / natW, boxH / natH);
  const drawW = natW * scale;
  const drawH = natH * scale;
  const offsetX = boxX + (boxW - drawW) / 2;
  const offsetY = boxY + (boxH - drawH) / 2;
  ctx.drawImage(img, offsetX, offsetY, drawW, drawH);
}

/**
 * Generates an exported Blob (PNG, flattened JPEG, or self-contained vector SVG)
 * entirely in the user's browser without any server round-trip.
 *
 * Operates on an immutable snapshot of `(encodedPayload, design, exportOptions)`
 * so concurrent UI state transitions never corrupt an in-flight export.
 */
export async function exportQrCodeBlob(
  encodedPayload: string,
  design: QRDesign,
  exportOptions: ExportOptions
): Promise<Blob> {
  if (typeof window === "undefined" || typeof document === "undefined") {
    throw new Error("QR export is only supported in a browser environment.");
  }

  if (!encodedPayload || encodedPayload.length === 0) {
    throw new Error("Cannot export an empty QR payload.");
  }

  // Capture an immutable snapshot of the design state at the moment export starts
  const designSnapshot: QRDesign = structuredClone(design);

  const capacity = estimateQrCapacity(
    encodedPayload,
    designSnapshot.errorCorrection
  );
  if (capacity.isExceeded) {
    throw new Error(
      `Payload length (${capacity.byteLength} UTF-8 bytes) exceeds maximum QR capacity (${capacity.maxBytes} bytes) at error correction level ${designSnapshot.errorCorrection}.`
    );
  }

  const exportWidth = Math.min(
    MAX_EXPORT_DIMENSION,
    Math.max(
      MIN_EXPORT_DIMENSION,
      Math.round(exportOptions.width || designSnapshot.width)
    )
  );
  const exportHeight = Math.min(
    MAX_EXPORT_DIMENSION,
    Math.max(
      MIN_EXPORT_DIMENSION,
      Math.round(exportOptions.height || designSnapshot.height)
    )
  );

  const isJpeg = exportOptions.format === "jpeg";
  const jpegQuality = Math.min(
    1,
    Math.max(0.1, exportOptions.quality ?? DEFAULT_JPEG_QUALITY)
  );

  const fallbackCompositeColor = normalizeHexColor(
    exportOptions.backgroundColor || "#FFFFFF",
    "#FFFFFF"
  );

  // For JPEG exports, transparent backgrounds must be composited against a solid color (#FFFFFF by default)
  const effectiveDesign: QRDesign = {
    ...designSnapshot,
    width: exportWidth,
    height: exportHeight,
    background: isJpeg
      ? {
          ...(designSnapshot.background.transparent
            ? {
                color: fallbackCompositeColor,
                transparent: false,
              }
            : {
                ...designSnapshot.background,
                color: normalizeHexColor(
                  designSnapshot.background.color || "#FFFFFF",
                  "#FFFFFF"
                ),
                transparent: false,
              }),
        }
      : {
          ...designSnapshot.background,
        },
  };

  const mod = await import("qr-code-styling");
  const QRCodeStyling = mod.default;

  const engineOptions = mapDesignToEngineOptions(
    encodedPayload,
    effectiveDesign,
    "svg"
  );

  const qr = new QRCodeStyling(engineOptions);
  const internalQr = qr as unknown as InternalQrCodeStyling;
  if (internalQr._svgDrawingPromise) {
    await internalQr._svgDrawingPromise;
  }

  const svgElement = internalQr._svg;
  if (!svgElement) {
    throw new Error("Failed to construct vector SVG element for QR export.");
  }

  const logoBox = finalizeStandaloneSvgElement(
    svgElement,
    effectiveDesign,
    engineOptions.margin ?? 0,
    internalQr._qr
  );

  // 1. Standalone Vector SVG Export
  if (exportOptions.format === "svg") {
    const serializedSvg = new XMLSerializer().serializeToString(svgElement);
    const xmlDocumentString = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n${serializedSvg}`;

    const svgReport = inspectSvgContent(xmlDocumentString);
    if (!svgReport.isValidXml) {
      throw new Error(
        `Exported SVG failed validation: ${svgReport.errors.join("; ")}`
      );
    }

    return new Blob([xmlDocumentString], {
      type: "image/svg+xml;charset=utf-8",
    });
  }

  // 2. Raster PNG / JPEG Export via native HTMLCanvasElement in real browsers
  if (canUseBrowser2dCanvas()) {
    const canvas = document.createElement("canvas");
    canvas.width = exportWidth;
    canvas.height = exportHeight;

    try {
      const ctx = canvas.getContext("2d");
      if (!ctx) {
        throw new Error("Unable to acquire 2D rendering context for export.");
      }

      if (isJpeg) {
        ctx.fillStyle = effectiveDesign.background.color || "#FFFFFF";
        ctx.fillRect(0, 0, exportWidth, exportHeight);
      } else {
        ctx.clearRect(0, 0, exportWidth, exportHeight);
      }

      // Clone the SVG without the <g id="openqr-logo-group"> so we can composite the logo
      // directly onto the 2D canvas using a top-level Image element for 100% browser reliability.
      const baseSvgClone = svgElement.cloneNode(true) as SVGSVGElement;
      const clonedLogoGroup = baseSvgClone.querySelector("#openqr-logo-group");
      clonedLogoGroup?.parentNode?.removeChild(clonedLogoGroup);

      const baseSvgString = new XMLSerializer().serializeToString(baseSvgClone);
      const baseSvgDataUri = `data:image/svg+xml;base64,${encodeUtf8ToBase64(baseSvgString)}`;
      const qrLayerImg = await loadImageElement(baseSvgDataUri);
      ctx.drawImage(qrLayerImg, 0, 0, exportWidth, exportHeight);

      if (logoBox) {
        const logoImg = await loadImageElement(logoBox.source);
        ctx.save();
        traceRoundedRectPath(
          ctx,
          logoBox.x,
          logoBox.y,
          logoBox.width,
          logoBox.height,
          logoBox.rx
        );
        ctx.clip();

        if (logoBox.bgFill) {
          ctx.fillStyle = logoBox.bgFill;
          ctx.fillRect(
            logoBox.x,
            logoBox.y,
            logoBox.width,
            logoBox.height
          );
        }

        drawLogoPreserveAspectRatio(
          ctx,
          logoImg,
          logoBox.innerX,
          logoBox.innerY,
          logoBox.innerWidth,
          logoBox.innerHeight
        );
        ctx.restore();
      }

      const mimeType = isJpeg ? "image/jpeg" : "image/png";
      const blob = await new Promise<Blob | null>((resolve) => {
        canvas.toBlob(
          (result) => resolve(result),
          mimeType,
          isJpeg ? jpegQuality : undefined
        );
      });

      if (!blob) {
        throw new Error(
          `Failed to encode ${exportOptions.format.toUpperCase()} image blob.`
        );
      }

      return blob;
    } finally {
      // Deterministic cleanup of temporary offscreen canvas buffer
      canvas.width = 0;
      canvas.height = 0;
    }
  }

  // 3. Deterministic software rasterizer fallback for non-canvas test environments (jsdom)
  if (!internalQr._qr) {
    throw new Error("QR matrix unavailable for raster export.");
  }

  const rgba = renderQrMatrixToRgbaBuffer(
    internalQr._qr,
    effectiveDesign,
    engineOptions.margin ?? 0,
    isJpeg
  );

  if (isJpeg) {
    const jpegBytes = encodeRgbaToFallbackJpegBytes(
      rgba,
      exportWidth,
      exportHeight,
      jpegQuality
    );
    return new Blob([new Uint8Array(jpegBytes)], { type: "image/jpeg" });
  }

  const pngBytes = encodeRgbaToPngBytes(rgba, exportWidth, exportHeight);
  return new Blob([new Uint8Array(pngBytes)], { type: "image/png" });
}
